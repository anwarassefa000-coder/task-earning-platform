// Translation function
function translate(key, language = 'en') {
  if (language === 'am') {
    return amharicTranslations[key] || key;
  }
  return key; // English is default
}

// Format currency with Amharic numerals if needed
function formatCurrency(amount, language = 'en') {
  const formatter = new Intl.NumberFormat(language === 'am' ? 'am-ET' : 'en-US', {
    style: 'currency',
    currency: 'USD'
  });
  return formatter.format(amount);
}

// Format date with Amharic calendar option
function formatDate(date, language = 'en') {
  const options = {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
    hour: '2-digit',
    minute: '2-digit'
  };
  const locale = language === 'am' ? 'am-ET' : 'en-US';
  return new Date(date).toLocaleDateString(locale, options);
}

